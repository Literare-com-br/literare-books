import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import ffmpeg from 'ffmpeg-static';
import { spawnSync } from 'node:child_process';

const root = process.cwd();
const sourceRoot = path.resolve(root, 'assets-source');
const imageRoot = path.resolve(root, 'public/images');
const outputRoot = path.resolve(root, 'public/images/optimized');
for (const target of [sourceRoot, imageRoot, outputRoot]) {
  if (!target.startsWith(root + path.sep)) throw new Error('Media paths must stay inside this workspace.');
}
await fs.mkdir(outputRoot, { recursive: true });
const manifest = {};
let before = 0, after = 0;
async function processDirectory(directory, relative = '') {
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    if (entry.name === 'optimized') continue;
    const rel = path.join(relative, entry.name);
    if (entry.isDirectory()) { await processDirectory(path.join(directory, entry.name), rel); continue; }
    if (!/\.(png|jpe?g)$/i.test(entry.name)) continue;
    const source = path.join(directory, entry.name);
    const buffer = await fs.readFile(source);
    const meta = await sharp(buffer).metadata();
    const isCover = rel.startsWith('books' + path.sep);
    const isLogo = /logo/i.test(entry.name);
    const sizes = isCover ? [240,480] : isLogo ? [480] : [480,800,1100];
    const base = rel.replace(/\.[^.]+$/, '').replaceAll(path.sep, '-');
    const variants = [];
    for (const width of sizes.filter((w,i,all) => i === 0 || w <= (meta.width ?? w) || all[i-1] < (meta.width ?? w))) {
      const file = `${base}-${width}.webp`;
      const result = await sharp(buffer).resize({width,withoutEnlargement:true}).webp({quality:isLogo?100:92,effort:6,lossless:isLogo}).toBuffer({resolveWithObject:true});
      await fs.writeFile(path.join(outputRoot,file),result.data);
      variants.push({src:`/images/optimized/${file}`,width:result.info.width,bytes:result.data.length});
    }
    const largest = variants.at(-1);
    manifest['/images/'+rel.replaceAll(path.sep,'/')] = {src:largest.src,srcSet:variants.map(v=>`${v.src} ${v.width}w`).join(', '),width:meta.width,height:meta.height};
    before += buffer.length; after += largest.bytes;
    const backup = path.join(sourceRoot,'images',rel);
    if (!backup.startsWith(sourceRoot+path.sep)) throw new Error('Invalid backup path');
    await fs.mkdir(path.dirname(backup),{recursive:true});
    await fs.rename(source,backup);
  }
}
await processDirectory(imageRoot);
if (Object.keys(manifest).length) await fs.writeFile('src/data/image-assets.ts','// Generated by scripts/optimize-media.mjs. Originals retained in assets-source.\nexport const imageAssets: Record<string, {src:string;srcSet:string;width:number;height:number}> = '+JSON.stringify(manifest,null,2)+';\n');
await fs.mkdir('assets-source/videos',{recursive:true});
const originalVideo='public/videos/literare-phone.mp4';
try {
  await fs.access(originalVideo);
  const result=spawnSync(ffmpeg,['-hide_banner','-loglevel','error','-y','-i',originalVideo,'-map','0:v:0','-c:v','copy','-an','-movflags','+faststart','public/videos/literare-phone.optimized.mp4'],{windowsHide:true});
  if(result.status!==0)throw new Error(result.stderr?.toString()||'Video optimization failed');
  await fs.rename(originalVideo,'assets-source/videos/literare-phone.mp4');
} catch(error) {if(error.code!=='ENOENT')throw error;}
for(const weight of [400,500,600,700]) await fs.copyFile(`node_modules/@fontsource/poppins/files/poppins-latin-${weight}-normal.woff2`,`public/fonts/Poppins-${weight}.woff2`);
await fs.copyFile('node_modules/@fontsource/poppins/LICENSE','public/fonts/Poppins-OFL.txt');
console.log(JSON.stringify({images:Object.keys(manifest).length,originalImageBytes:before,largestWebpBytes:after}));
